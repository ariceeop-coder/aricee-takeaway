// Generates the server-side copy of the customisation/price data from menu-extras.js (compact form).
const fs = require('fs'); const path = require('path');
global.window = {}; eval(fs.readFileSync(path.join(__dirname, '../menu-extras.js'), 'utf8'));
const X = window.MENU_EXTRAS;
// itemGroups: store each distinct group list once, with the item ids that use it written as ranges (m1-m14,m16)
const sets = {}; 
Object.entries(X.itemGroups).forEach(([id, g]) => { (sets[g.join(',')] = sets[g.join(',')] || []).push(id); });
const compress = ids => {
  const parsed = ids.map(i => ({ p: i[0], n: Number(i.slice(1)) })).sort((a, b) => a.p < b.p ? -1 : a.p > b.p ? 1 : a.n - b.n);
  const out = []; let i = 0;
  while (i < parsed.length) { let j = i; while (j + 1 < parsed.length && parsed[j + 1].p === parsed[i].p && parsed[j + 1].n === parsed[j].n + 1) j++;
    out.push(j > i ? parsed[i].p + parsed[i].n + '-' + parsed[j].p + parsed[j].n : parsed[i].p + parsed[i].n); i = j + 1; }
  return out.join(' ');
};
const setsOut = Object.entries(sets).map(([g, ids]) => [g.split(','), compress(ids)]);
const header = '// GENERATED by tools/build_extras_ts.js from menu-extras.js - do not edit by hand\n';
const body = `const RAW: any = ${JSON.stringify({ hours: X.hours, groups: X.groups, newItems: X.newItems })};
const SETS: any[] = ${JSON.stringify(setsOut)};
const itemGroups: Record<string, string[]> = {};
for (const [groups, ranges] of SETS) {
  for (const part of ranges.split(' ')) {
    const [a, b] = part.split('-'); const p = a[0]; const from = Number(a.slice(1)); const to = b ? Number(b.slice(1)) : from;
    for (let n = from; n <= to; n++) itemGroups[p + n] = groups;
  }
}
export const X: any = { ...RAW, itemGroups };
`;
fs.writeFileSync(path.join(__dirname, '../supabase/functions/_shared/extras.ts'), header + body);
console.log('extras.ts written', (header + body).length, 'bytes');
